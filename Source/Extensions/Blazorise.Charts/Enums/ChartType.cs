namespace Blazorise.Charts;

/// <summary>
/// Lists the supported chart type values.
/// </summary>
public enum ChartType
{
    /// <summary>
    /// Renders data as a line chart.
    /// </summary>
    Line,
    /// <summary>
    /// Renders data as a bar chart.
    /// </summary>
    Bar,
    /// <summary>
    /// Renders data as a pie chart.
    /// </summary>
    Pie,
    /// <summary>
    /// Renders data as a doughnut chart.
    /// </summary>
    Doughnut,
    /// <summary>
    /// Renders data as a polar area chart.
    /// </summary>
    PolarArea,
    /// <summary>
    /// Renders data as a radar chart.
    /// </summary>
    Radar,
    /// <summary>
    /// Renders data as a scatter chart.
    /// </summary>
    Scatter,
    /// <summary>
    /// Renders data as a bubble chart.
    /// </summary>
    Bubble,
}