namespace Blazorise.Ribbon;

/// <summary>
/// Defines how commands are arranged within a ribbon group.
/// </summary>
public enum RibbonGroupLayout
{
    /// <summary>
    /// Arranges explicit ribbon columns beside full-height commands.
    /// </summary>
    Columns,

    /// <summary>
    /// Arranges explicit ribbon rows vertically.
    /// </summary>
    Rows,
}