namespace Blazorise.Ribbon;

/// <summary>
/// Defines the command layout within a ribbon group.
/// </summary>
public enum RibbonItemSize
{
    /// <summary>
    /// Displays an icon with an accessible text label.
    /// </summary>
    Small,

    /// <summary>
    /// Displays an icon beside its text.
    /// </summary>
    Medium,

    /// <summary>
    /// Displays an icon above its text and occupies the full group height.
    /// </summary>
    Large,
}