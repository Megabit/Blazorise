namespace Blazorise.Ribbon;

/// <summary>
/// Defines the predefined color selections available in a ribbon color menu.
/// </summary>
public enum RibbonColorPalette
{
    /// <summary>
    /// Provides eight common colors in a compact selection.
    /// </summary>
    Simple,

    /// <summary>
    /// Provides a selection of ten standard colors.
    /// </summary>
    Standard,

    /// <summary>
    /// Provides base colors with tint and shade rows, followed by standard colors.
    /// </summary>
    Extended,
}