namespace Blazorise.SpinKit;

/// <summary>
/// Available CSS animations for a <see cref="SpinKit"/> spinner.
/// </summary>
public enum SpinKitType
{
    /// <summary>
    /// A single folding plane.
    /// </summary>
    Plane,

    /// <summary>
    /// Dots chasing one another around a ring.
    /// </summary>
    Chase,

    /// <summary>
    /// A pair of alternating bouncing dots.
    /// </summary>
    Bounce,

    /// <summary>
    /// Bars rising and falling as a wave.
    /// </summary>
    Wave,

    /// <summary>
    /// A shape that expands and fades rhythmically.
    /// </summary>
    Pulse,

    /// <summary>
    /// Three dots flowing in sequence.
    /// </summary>
    Flow,

    /// <summary>
    /// Two dots swinging around a shared center.
    /// </summary>
    Swing,

    /// <summary>
    /// Dots rotating around a circular path.
    /// </summary>
    Circle,

    /// <summary>
    /// A circular sequence of fading dots.
    /// </summary>
    CircleFade,

    /// <summary>
    /// A grid of cubes pulsing in sequence.
    /// </summary>
    Grid,

    /// <summary>
    /// Cubes folding into one another.
    /// </summary>
    Fold,

    /// <summary>
    /// Cubes travelling around a compact path.
    /// </summary>
    Wander,
}