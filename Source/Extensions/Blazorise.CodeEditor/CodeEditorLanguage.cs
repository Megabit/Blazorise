namespace Blazorise.CodeEditor;

/// <summary>
/// Defines common code editor language identifiers.
/// </summary>
public static class CodeEditorLanguage
{
    /// <summary>Unformatted plain-text content.</summary>
    public const string PlainText = "plaintext";
    /// <summary>C# source code.</summary>
    public const string CSharp = "csharp";
    /// <summary>Cascading Style Sheets.</summary>
    public const string Css = "css";
    /// <summary>HTML markup.</summary>
    public const string Html = "html";
    /// <summary>JavaScript source code.</summary>
    public const string JavaScript = "javascript";
    /// <summary>JSON documents.</summary>
    public const string Json = "json";
    /// <summary>Markdown documents.</summary>
    public const string Markdown = "markdown";
    /// <summary>Razor component markup.</summary>
    public const string Razor = "razor";
    /// <summary>SQL statements and scripts.</summary>
    public const string Sql = "sql";
    /// <summary>TypeScript source code.</summary>
    public const string TypeScript = "typescript";
    /// <summary>XML documents.</summary>
    public const string Xml = "xml";
    /// <summary>YAML documents.</summary>
    public const string Yaml = "yaml";
}