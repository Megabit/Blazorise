namespace Blazorise;

/// <summary>
/// Defines the placement of step items relative to their content.
/// </summary>
public enum StepPosition
{
    /// <summary>
    /// Places the steps above their content.
    /// </summary>
    Top,

    /// <summary>
    /// Places the steps below their content.
    /// </summary>
    Bottom,

    /// <summary>
    /// Places the steps at the start side of their content.
    /// </summary>
    Start,

    /// <summary>
    /// Places the steps at the end side of their content.
    /// </summary>
    End,
}